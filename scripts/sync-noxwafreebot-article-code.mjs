import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const NoxCoreDevScriptDirectory = dirname(fileURLToPath(import.meta.url));
const NoxCoreDevProjectRoot = resolve(NoxCoreDevScriptDirectory, "..");
const NoxCoreDevDefinitions = [
  { id: "package", label: "package.json", language: "json", path: "examples/NoxWaFreeBot/package.json" },
  { id: "config", label: "config.js", language: "javascript", path: "examples/NoxWaFreeBot/config.js" },
  { id: "index", label: "index.js", language: "javascript", path: "examples/NoxWaFreeBot/index.js" },
  { id: "handler", label: "handler.js", language: "javascript", path: "examples/NoxWaFreeBot/handler.js" },
  { id: "commands", label: "commands.js", language: "javascript", path: "examples/NoxWaFreeBot/commands.js" },
  { id: "newsletters", label: "newsletters.js", language: "javascript", path: "examples/NoxWaFreeBot/newsletters.js" },
  { id: "groups", label: "group-events.js", language: "javascript", path: "examples/NoxWaFreeBot/group-events.js" },
  { id: "readme", label: "README.md", language: "markdown", path: "examples/NoxWaFreeBot/README.md" },
  { id: "ignore", label: ".gitignore", language: "text", path: "examples/NoxWaFreeBot/.gitignore" },
  { id: "mockTest", label: "scripts/mock-test.mjs", language: "javascript", path: "examples/NoxWaFreeBot/scripts/mock-test.mjs" },
];

const NoxCoreDevCode = {};
for (const NoxCoreDevDefinition of NoxCoreDevDefinitions) {
  NoxCoreDevCode[NoxCoreDevDefinition.id] = {
    label: NoxCoreDevDefinition.label,
    language: NoxCoreDevDefinition.language,
    code: await readFile(resolve(NoxCoreDevProjectRoot, NoxCoreDevDefinition.path), "utf8"),
  };
}

const NoxCoreDevOutput = "// Generated by scripts/sync-noxwafreebot-article-code.mjs; edit the source files in examples/NoxWaFreeBot instead.\n"
  + "export const NoxWaFreeBotCode = Object.freeze("
  + JSON.stringify(NoxCoreDevCode, null, 2)
  + ");\n";
await writeFile(resolve(NoxCoreDevProjectRoot, "src/data/articles/noxwafreebot-code.js"), NoxCoreDevOutput, "utf8");
process.stdout.write("Synced NoxWaFreeBot source files into the blog code blocks.\n");
